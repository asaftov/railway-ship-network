#!/usr/bin/env node
// Reads a Heroku app's Procfile and app.json (and optionally `heroku addons --json` output) and writes:
//   - a migration plan (markdown) to stdout
//   - a draft .railway/railway.ts the user can review before `railway config plan`
//
// Usage: node plan.mjs [--dir <app dir>] [--repo owner/name] [--addons addons.json] [--write]
// Nothing is applied. --write saves .railway/railway.ts in the app dir (refuses to overwrite).

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => {
    if (a.startsWith("--")) acc.push([a.slice(2), all[i + 1] && !all[i + 1].startsWith("--") ? all[i + 1] : true]);
    return acc;
  }, []),
);
const dir = path.resolve(args.dir || ".");

function read(file) {
  const p = path.join(dir, file);
  return fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
}

function gitRepo() {
  try {
    const url = execFileSync("git", ["-C", dir, "remote", "get-url", "origin"], { encoding: "utf8" }).trim();
    const m = url.match(/github\.com[:/](.+?)(\.git)?$/);
    return m ? m[1] : null;
  } catch {
    return null;
  }
}

// Procfile: "name: command"
const procfile = read("Procfile");
const processes = [];
if (procfile) {
  for (const line of procfile.split("\n")) {
    const m = line.match(/^([A-Za-z0-9_-]+):\s*(.+)$/);
    if (m) processes.push({ name: m[1], command: m[2].trim() });
  }
}

const appJson = read("app.json") ? JSON.parse(read("app.json")) : {};
const addonsFromJson = (appJson.addons || []).map((a) => (typeof a === "string" ? a : a.plan || ""));
let addonsFromCli = [];
if (args.addons && fs.existsSync(args.addons)) {
  const list = JSON.parse(fs.readFileSync(args.addons, "utf8"));
  addonsFromCli = list.map((a) => a.addon_service?.name || a.plan?.name || "");
}
const addons = [...new Set([...addonsFromJson, ...addonsFromCli].map((a) => a.split(":")[0]).filter(Boolean))];

const ADDON_MAP = {
  "heroku-postgresql": { railway: "postgres", note: "Railway Postgres. Restore from a Heroku backup (see step 5)." },
  "heroku-redis": { railway: "redis", note: "Railway Redis. Usually a cache or queue: start empty unless it holds durable data." },
  "rediscloud": { railway: "redis", note: "Railway Redis." },
  "scheduler": { railway: "cron", note: "Recreate each Heroku Scheduler job as a cron service (jobs aren't exported by the CLI; copy them from the Scheduler dashboard)." },
  "papertrail": { railway: null, note: "Railway has built-in logs; keep Papertrail only if you need its retention." },
  "sendgrid": { railway: null, note: "Keep the SendGrid account; copy its API key with the other config vars." },
  "heroku-kafka": { railway: null, note: "No managed Kafka on Railway; keep the external cluster or deploy a Kafka template." },
};

const releaseProc = processes.find((p) => p.name === "release");
const runtime = processes.filter((p) => p.name !== "release");
const hasDb = addons.includes("heroku-postgresql");
const hasRedis = addons.some((a) => ADDON_MAP[a]?.railway === "redis");
const repo = args.repo || gitRepo() || "OWNER/REPO";

// Draft IaC
const lines = [];
lines.push(`// Draft generated by heroku-to-railway/plan.mjs. Review before running \`railway config plan\`.`);
const imports = ["defineRailway", "github", "preserve", "project", "service", ...(hasDb ? ["postgres"] : []), ...(hasRedis ? ["redis"] : [])];
lines.push(`import { ${imports.sort().join(", ")} } from "railway/iac";`, "");
lines.push(`export default defineRailway(() => {`);
lines.push(`  const source = github("${repo}");`);
if (hasDb) lines.push(`  const db = postgres("postgres");`);
if (hasRedis) lines.push(`  const cache = redis("redis");`);
const envLines = [
  ...(hasDb ? [`    DATABASE_URL: db.env.DATABASE_URL,`] : []),
  ...(hasRedis ? [`    REDIS_URL: cache.env.REDIS_URL,`] : []),
  `    // Copy the rest from \`heroku config --shell\` into the dashboard's Raw Editor; preserve() keeps them.`,
  `    SECRET_KEY_BASE: preserve(),`,
];
lines.push(`  const env = {`, ...envLines, `  };`, "");
const names = [];
for (const p of runtime) {
  const svc = p.name === "web" ? "web" : p.name;
  names.push(svc);
  const opts = [`    source,`, `    start: ${JSON.stringify(p.command)},`];
  if (p.name === "web" && releaseProc) opts.push(`    preDeploy: ${JSON.stringify(releaseProc.command)},`);
  if (p.name === "web" && args.healthcheck) opts.push(`    healthcheck: ${JSON.stringify(args.healthcheck)},`);
  opts.push(`    env,`);
  lines.push(`  const ${svc.replace(/[^A-Za-z0-9_]/g, "_")} = service(${JSON.stringify(svc)}, {`, ...opts, `  });`);
}
if (addons.includes("scheduler")) {
  lines.push(
    `  // One cron service per Heroku Scheduler job. Example: nightly at 03:00 UTC.`,
    `  const nightly_job = service("nightly-job", {`,
    `    source,`,
    `    start: "REPLACE_WITH_SCHEDULER_COMMAND",`,
    `    deploy: { cronSchedule: "0 3 * * *", restartPolicyType: "NEVER" },`,
    `    env,`,
    `  });`,
  );
  names.push("nightly-job");
}
const resources = [...(hasDb ? ["db"] : []), ...(hasRedis ? ["cache"] : []), ...names.map((n) => n.replace(/[^A-Za-z0-9_]/g, "_"))];
lines.push("", `  return project(${JSON.stringify(appJson.name || path.basename(dir))}, { resources: [${resources.join(", ")}] });`, `});`, "");
const draft = lines.join("\n");

// Plan
const plan = [];
plan.push(`# Heroku → Railway migration plan: ${appJson.name || path.basename(dir)}`, "");
plan.push(`## Processes`, "");
if (!processes.length) plan.push(`No Procfile found. Railpack will detect the start command; confirm it before deploying.`, "");
for (const p of processes) {
  if (p.name === "release") plan.push(`- **release** \`${p.command}\` → pre-deploy command on the web service (runs before each deploy).`);
  else if (p.name === "web") plan.push(`- **web** \`${p.command}\` → service \`web\` with a public domain. Railway sets \`PORT\`.`);
  else plan.push(`- **${p.name}** \`${p.command}\` → separate service \`${p.name}\` (no public domain). Railway runs one process per service.`);
}
plan.push("", `## Add-ons`, "");
if (!addons.length) plan.push(`None detected in app.json. Run \`heroku addons -a <app> --json > addons.json\` and pass \`--addons addons.json\`.`);
for (const a of addons) plan.push(`- **${a}** → ${ADDON_MAP[a]?.note ?? "No direct Railway equivalent; keep it external and copy its config vars."}`);
plan.push(
  "",
  `## Steps`,
  "",
  `1. \`railway login\`, then \`railway init\` (new project) or \`railway link\` (existing).`,
  `2. Review the draft \`.railway/railway.ts\`, then \`npm i -D railway\`, \`railway config plan\` and, after the user confirms, \`railway config apply\`.`,
  `3. Config vars: \`heroku config --shell -a <app>\`. Drop DATABASE_URL and REDIS_URL (Railway provides them), then paste the rest into each service's Variables → Raw Editor.`,
  `4. Deploy and check: \`railway logs\`, hit the healthcheck, run the app's smoke test.`,
  ...(hasDb
    ? [
        `5. Database, in a maintenance window: \`heroku maintenance:on -a <app>\`, \`heroku pg:backups:capture -a <app>\`, \`curl -o latest.dump "$(heroku pg:backups:url -a <app>)"\`, then \`pg_restore --verbose --no-owner --no-acl -d "$DATABASE_PUBLIC_URL" latest.dump\` using the Railway Postgres public URL. Verify row counts before cutover.`,
      ]
    : []),
  `${hasDb ? 6 : 5}. Cutover: add the custom domain to the web service, update DNS, keep the Heroku app in maintenance mode (not deleted) until traffic and data are verified.`,
);

console.log(plan.join("\n"));
console.log("\n---\nDraft .railway/railway.ts:\n");
console.log(draft);

if (args.write) {
  const target = path.join(dir, ".railway", "railway.ts");
  if (fs.existsSync(target)) {
    console.error(`\nNot writing: ${target} already exists.`);
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, draft);
  console.error(`\nWrote ${target}`);
}
